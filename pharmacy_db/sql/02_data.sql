-- Проверка: сколько строк в каждой таблице
SELECT 'categories' AS table_name, COUNT(*) AS rows_count FROM categories
UNION ALL SELECT 'manufacturers', COUNT(*) FROM manufacturers
UNION ALL SELECT 'suppliers', COUNT(*) FROM suppliers
UNION ALL SELECT 'storage_locations', COUNT(*) FROM storage_locations
UNION ALL SELECT 'employees', COUNT(*) FROM employees
UNION ALL SELECT 'customers', COUNT(*) FROM customers
UNION ALL SELECT 'products', COUNT(*) FROM products
UNION ALL SELECT 'batches', COUNT(*) FROM batches
UNION ALL SELECT 'receipts', COUNT(*) FROM receipts
UNION ALL SELECT 'receipt_items', COUNT(*) FROM receipt_items
UNION ALL SELECT 'shipments', COUNT(*) FROM shipments
UNION ALL SELECT 'shipment_items', COUNT(*) FROM shipment_items
UNION ALL SELECT 'write_offs', COUNT(*) FROM write_offs;
